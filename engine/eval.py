def evaluate(board: chess.Board) -> int:
    """
    Static evaluation of `board`, in centipawns, from White's perspective.
    Positive = good for White, negative = good for Black.
    """
    if board.is_checkmate():
        return -100000 if board.turn == chess.WHITE else 100000
    if board.is_stalemate() or board.is_insufficient_material() or \
            board.is_seventyfive_moves() or board.is_fivefold_repetition():
        return 0

    score = 0
    for square, piece in board.piece_map().items():
        value = PIECE_VALUES[piece.piece_type]
        pst_index = square if piece.color == chess.WHITE else chess.square_mirror(square)
        pst_value = PST[piece.piece_type][pst_index]

        if piece.color == chess.WHITE:
            score += value + pst_value
        else:
            score -= value + pst_value

    return score
